
# positive indexing
s = 'hello world'
print(s[3])


# Negative Indexing
a = 'hello world'
print(a[-5])

# Slicing

b = 'hello world'
print(b[0:5])
print(b[5:])
print(b[:3])
print(b[:])
# step size
print(b[0:6:2])

# Negative Slicing

print(b[6:0:-1])

print(b[::-1])

print(b[-5:])
print(b[-1:-6:-1])